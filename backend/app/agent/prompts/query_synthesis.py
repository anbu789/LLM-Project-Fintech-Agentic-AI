def build_query_synthesis_prompt(
    query: str,
    schema_context: Dict[str, Any],
    conversation_history: Optional[List[Dict[str, Any]]] = None,
) -> str:
    """Builds user prompt embedding schema context and conversation history."""
    parts: List[str] = []

    # 1. Multi-turn conversation context
    if conversation_history:
        recent = conversation_history[-4:]
        ctx_lines = []
        for msg in recent:
            role = msg.get("role", "user")
            content = (msg.get("content") or "").strip()
            if content:
                ctx_lines.append(f"[{role}]: {content}")
        if ctx_lines:
            parts.append("## Prior Conversation Context")
            parts.extend(ctx_lines)
            parts.append("")

    # 2. Schema Context
    parts.append("## Retrieved Schema Context")
    collections = schema_context.get("collections", {})
    if collections:
        for col_name, col_meta in collections.items():
            parts.append(f"### Collection: `{col_name}` (Primary Key: `{col_meta.get('primary_key')}`)")
            fields = col_meta.get("fields", {})
            field_lines = []
            if isinstance(fields, dict):
                for f_name, f_data in fields.items():
                    f_type = f_data.get("data_type", "string") if isinstance(f_data, dict) else "string"
                    f_desc = f_data.get("description", "") if isinstance(f_data, dict) else ""
                    enums = f_data.get("allowed_values") if isinstance(f_data, dict) else None
                    enum_str = f" [Allowed: {', '.join(enums)}]" if enums else ""
                    field_lines.append(f"  - `{f_name}` ({f_type}): {f_desc}{enum_str}")
            elif isinstance(fields, list):
                for f_name in fields:
                    field_lines.append(f"  - `{f_name}`")
            parts.extend(field_lines[:25])  # Cap fields per collection for context bound
    else:
        parts.append("No specific collection schema retrieved. Use canonical banking collections.")

    # 3. Verified Relationships
    relationships = schema_context.get("relevant_relationships", [])
    if relationships:
        parts.append("\n### Verified Join Relationships")
        for rel in relationships:
            parts.append(f"  - Join `{rel.get('from')}` with `{rel.get('to')}` ({rel.get('cardinality')})")

    # 4. Unsupported Concept Warnings
    unsupported = schema_context.get("unsupported_concepts", [])
    if unsupported:
        parts.append("\n### Unsupported Concept Warnings")
        for warn in unsupported:
            parts.append(f"  - WARNING: {warn.get('warning')}")

    # 5. User Query
    parts.append("\n## Current User Inquiry")
    parts.append(query)
    parts.append("\nGenerate the JSON aggregation pipeline specification according to the system instructions.")

    return "\n".join(parts)


