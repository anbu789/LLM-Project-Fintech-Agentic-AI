from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, model_validator

# ---------------------------------------------------------------------------
# Pydantic Schema for Query Synthesis Output
# ---------------------------------------------------------------------------

class PipelineSynthesisOutput(BaseModel):
    """Structured candidate aggregation pipeline generated by Node 4."""
    model_config = ConfigDict(populate_by_name=True, extra="allow")

    target_collection: str = Field(..., description="Root collection name to run pipeline against")
    pipeline: List[Dict[str, Any]] = Field(default_factory=list, description="MongoDB aggregation pipeline stages")
    explanation: str = Field(default="", description="Natural language explanation of the query logic")
    unsupported_concepts_identified: List[str] = Field(
        default_factory=list,
        description="List of requested concepts that are not supported by the schema"
    )
    assumptions: List[str] = Field(default_factory=list, description="Assumptions made during query generation")
    referenced_fields: List[str] = Field(default_factory=list, description="Fields referenced by pipeline")

    @model_validator(mode="before")
    @classmethod
    def _normalize_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "target_collection" not in data and "selected_collection" in data:
                data["target_collection"] = data["selected_collection"]
            if "explanation" not in data:
                data["explanation"] = data.get("query_explanation", "")
        return data


