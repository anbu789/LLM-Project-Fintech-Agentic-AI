# Deterministic Mock Synthesizer for Unit Testing & Offline Execution
# ---------------------------------------------------------------------------

def mock_synthesize_query(
    query: str,
    schema_context: Dict[str, Any],
    conversation_history: Optional[List[Dict[str, Any]]] = None,
) -> PipelineSynthesisOutput:
    """Deterministic pipeline synthesizer for offline unit testing without API keys."""
    q = query.lower().strip()

    # Context resolution from prior turn if elliptical follow-up
    prior_user_msg = ""
    if conversation_history:
        prior_user_msgs = [m.get("content", "") for m in conversation_history if m.get("role") == "user"]
        if prior_user_msgs:
            prior_user_msg = prior_user_msgs[-1].lower()

    # 1. Unsupported overdue debt / DPD check — strictly unmapped to defaulted loans
    if any(k in q for k in ("overdue debt", "overdue amount", "overdue loan", "overdue loans", "days past due", "dpd", "past due")):
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[],
            explanation=(
                "The requested concepts ('overdue_amount', 'days_past_due') are unsupported by the available loans schema. "
                "The schema contains only 'outstanding_amount' (remaining principal) and 'status' ('active', 'closed', 'defaulted'). "
                "In commercial banking, remaining principal on defaulted loans is distinct from overdue arrears/missed installments "
                "and cannot be substituted as overdue debt."
            ),
            unsupported_concepts_identified=["overdue_amount", "days_past_due"],
            assumptions=[]
        )

    # 1b. Supported: Calculate outstanding principal of defaulted loans
    if any(k in q for k in (
        "outstanding principal of defaulted",
        "defaulted loans and their outstanding principal",
        "total remaining principal of defaulted",
        "sum of outstanding for defaulted",
        "principal of defaulted",
        "outstanding amount of defaulted",
    )):
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[
                {"$match": {"status": "defaulted"}},
                {"$group": {"_id": None, "total_defaulted_principal": {"$sum": "$outstanding_amount"}}},
                {"$limit": 1}
            ],
            explanation="Calculated total outstanding principal of defaulted loans.",
            unsupported_concepts_identified=[],
            assumptions=["Aggregated loans.outstanding_amount for records where status is 'defaulted'"]
        )

    # 1c. Supported: Show defaulted loans list
    if any(k in q for k in ("defaulted loan", "defaulted loans", "loans in default", "show defaults")):
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[
                {"$match": {"status": "defaulted"}},
                {"$project": {"loan_id": 1, "customer_id": 1, "loan_type": 1, "principal_amount": 1, "outstanding_amount": 1, "status": 1}},
                {"$limit": 100}
            ],
            explanation="Retrieved loans with status 'defaulted'.",
            unsupported_concepts_identified=[],
            assumptions=["Filtered strictly by loans.status = 'defaulted'"]
        )

    # 1d. Multi-turn follow-up: "What about Coimbatore?" with city/customer context
    if ("what about" in q or "how about" in q) and any(c in q for c in ("coimbatore", "chennai", "mumbai", "delhi", "bangalore")):
        import re
        city_m = re.search(r"\b(coimbatore|chennai|mumbai|delhi|bangalore|kolkata|hyderabad|pune)\b", q)
        city_name = city_m.group(0).title() if city_m else "Coimbatore"
        return PipelineSynthesisOutput(
            target_collection="customers",
            pipeline=[
                {"$match": {"address.city": city_name}},
                {"$project": {"customer_id": 1, "first_name": 1, "last_name": 1, "address.city": 1, "credit_score": 1}},
                {"$limit": 100}
            ],
            explanation=f"Follow-up: Filtered customers located in {city_name}.",
            unsupported_concepts_identified=[],
            assumptions=[f"Inherited customer location query context from preceding turn for city '{city_name}'"]
        )

    # 2. Multi-turn follow-up: "Only show failed ones" with transaction context
    if "only show failed" in q or ("failed" in q and "transaction" not in q and "cust" in prior_user_msg):
        cust_id = "CUST001"
        if "cust" in prior_user_msg:
            import re
            m = re.search(r"cust\w+", prior_user_msg)
            if m:
                cust_id = m.group(0).upper()
        return PipelineSynthesisOutput(
            target_collection="transactions",
            pipeline=[
                {"$match": {"customer_id": cust_id, "status": "failed"}},
                {"$sort": {"transaction_date": -1}},
                {"$limit": 100}
            ],
            explanation=f"Follow-up: Filtered failed transactions for customer {cust_id}.",
            unsupported_concepts_identified=[],
            assumptions=["Applied customer filter from preceding conversation turn"]
        )

    # 3. Multi-turn follow-up: "Sort them by outstanding amount" with loan context
    if "sort them by outstanding" in q or ("outstanding" in q and "loan" not in q and "loan" in prior_user_msg):
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[
                {"$match": {"status": "active"}},
                {"$sort": {"outstanding_amount": -1}},
                {"$limit": 100}
            ],
            explanation="Follow-up: Sorted active loans by outstanding amount in descending order.",
            unsupported_concepts_identified=[],
            assumptions=["Retained active loan filter from preceding turn"]
        )

    # 4. Total customer count
    if any(k in q for k in ("how many customers", "customer count", "total customer", "count of customer")):
        return PipelineSynthesisOutput(
            target_collection="customers",
            pipeline=[{"$count": "total_customers"}],
            explanation="Counted total documents in the customers collection.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 5. Customers from a specific city (e.g. Chennai, Mumbai, Delhi)
    for city in ("chennai", "mumbai", "delhi", "bangalore", "kolkata", "hyderabad", "pune"):
        if city in q and "customer" in q:
            capitalized = city.capitalize()
            match_doc: Dict[str, Any] = {"city": capitalized}
            if "active" in q:
                match_doc["status"] = "active"
            return PipelineSynthesisOutput(
                target_collection="customers",
                pipeline=[
                    {"$match": match_doc},
                    {"$limit": 100}
                ],
                explanation=f"Filtered customers residing in {capitalized}.",
                unsupported_concepts_identified=[],
                assumptions=[]
            )

    # 6. Active customers
    if "active customer" in q or "active customers" in q:
        return PipelineSynthesisOutput(
            target_collection="customers",
            pipeline=[
                {"$match": {"status": "active"}},
                {"$limit": 100}
            ],
            explanation="Filtered customers with status active.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 7. Customer list (general)
    if "all customer" in q or "show customer" in q or "list customer" in q:
        return PipelineSynthesisOutput(
            target_collection="customers",
            pipeline=[{"$limit": 100}],
            explanation="Retrieved list of customers capped to default limit.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 8. Active loans
    if "active loan" in q or "active loans" in q:
        match_doc = {"status": "active"}
        if "above" in q or "greater" in q or "outstanding" in q or "lakh" in q:
            match_doc["outstanding_amount"] = {"$gt": 500000}
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[
                {"$match": match_doc},
                {"$limit": 100}
            ],
            explanation="Filtered loans where status is 'active'.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 9. Outstanding loan amount summary
    if any(k in q for k in ("total outstanding", "sum of outstanding", "outstanding loan amount", "sum of balance")):
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[
                {"$group": {"_id": None, "total_outstanding": {"$sum": "$outstanding_amount"}}}
            ],
            explanation="Calculated sum of outstanding_amount across all loan records.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 10. General loans list
    if "loan" in q:
        return PipelineSynthesisOutput(
            target_collection="loans",
            pipeline=[{"$limit": 100}],
            explanation="Retrieved loan records capped to default limit.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 11. Failed transactions
    if "failed transaction" in q or "failed transactions" in q:
        return PipelineSynthesisOutput(
            target_collection="transactions",
            pipeline=[
                {"$match": {"status": "failed"}},
                {"$sort": {"transaction_date": -1}},
                {"$limit": 100}
            ],
            explanation="Retrieved transactions with status 'failed', sorted by date descending.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 12. Transactions by specific customer (e.g. CUST001)
    if "transaction" in q and ("cust" in q or "customer" in q):
        import re
        cust_match = re.search(r"cust\w+", q)
        cust_val = cust_match.group(0).upper() if cust_match else "CUST001"
        return PipelineSynthesisOutput(
            target_collection="transactions",
            pipeline=[
                {"$match": {"customer_id": cust_val}},
                {"$sort": {"transaction_date": -1}},
                {"$limit": 100}
            ],
            explanation=f"Retrieved transactions for customer {cust_val}.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 13. Top merchants by transaction volume
    if "merchant" in q and ("volume" in q or "top" in q or "transaction" in q):
        return PipelineSynthesisOutput(
            target_collection="transactions",
            pipeline=[
                {"$group": {"_id": "$merchant_id", "total_volume": {"$sum": "$amount"}}},
                {"$sort": {"total_volume": -1}},
                {"$limit": 10}
            ],
            explanation="Grouped transactions by merchant_id and summed amount to find top merchants.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 14. Fraud alerts (high risk)
    if "fraud" in q or "alert" in q:
        return PipelineSynthesisOutput(
            target_collection="fraud_alerts",
            pipeline=[
                {"$match": {"risk_level": "high"}},
                {"$sort": {"created_at": -1}},
                {"$limit": 100}
            ],
            explanation="Retrieved fraud alerts flagged with high risk level.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 15. Count / group accounts
    if "account" in q and ("count" in q or "group" in q or "type" in q or "per" in q):
        return PipelineSynthesisOutput(
            target_collection="accounts",
            pipeline=[
                {"$group": {"_id": "$account_type", "count": {"$sum": 1}}},
                {"$sort": {"count": -1}},
                {"$limit": 100}
            ],
            explanation="Grouped accounts by account_type and counted totals.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 15b. Active accounts
    if "account" in q and "active" in q:
        return PipelineSynthesisOutput(
            target_collection="accounts",
            pipeline=[
                {"$match": {"status": "active"}},
                {"$limit": 100}
            ],
            explanation="Filtered accounts with status 'active'.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 16. KYC documents / pending verification
    if "kyc" in q:
        return PipelineSynthesisOutput(
            target_collection="kyc_documents",
            pipeline=[
                {"$match": {"verification_status": "pending"}},
                {"$limit": 100}
            ],
            explanation="Retrieved KYC documents pending verification.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 17. Support tickets
    if "ticket" in q or "support" in q:
        return PipelineSynthesisOutput(
            target_collection="support_tickets",
            pipeline=[
                {"$match": {"status": "open"}},
                {"$limit": 100}
            ],
            explanation="Retrieved open customer support tickets.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # 18. Branch customer count (join/group)
    if "branch" in q:
        return PipelineSynthesisOutput(
            target_collection="accounts",
            pipeline=[
                {"$group": {"_id": "$branch_id", "total_accounts": {"$sum": 1}}},
                {"$sort": {"total_accounts": -1}},
                {"$limit": 100}
            ],
            explanation="Grouped accounts by branch_id to count accounts per branch.",
            unsupported_concepts_identified=[],
            assumptions=[]
        )

    # Default fallback
    target_col = "customers"
    if schema_context.get("relevant_collections"):
        target_col = schema_context["relevant_collections"][0]
    elif schema_context.get("collections"):
        target_col = next(iter(schema_context["collections"].keys()))
    return PipelineSynthesisOutput(
        target_collection=target_col,
        pipeline=[{"$limit": 50}],
        explanation=f"Default bounded aggregation for collection {target_col}.",
        unsupported_concepts_identified=[],
        assumptions=["Applied default limit 50"]
    )
